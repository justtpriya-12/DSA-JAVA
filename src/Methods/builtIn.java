package Methods;

public class builtIn {
    public static void main(String[] args) {
        //print square root
        System.out.println(Math.sqrt(4));
        //print cube root
        System.out.println(Math.cbrt(1000));
        //print position form of number
        System.out.println(Math.abs(456));
        System.out.println(Math.abs(-45));
        //print greatest integer function
        System.out.println(Math.floor(5.6));
        System.out.println(Math.floor(-6.7));
        //print
        System.out.println(Math.ceil(5.6));
        System.out.println(Math.ceil(-7.6));
        //print min number
        System.out.println(Math.min(4.56,7.6));
        //print max number
        System.out.println(Math.max(7.8,65));
        System.out.println(Math.max(6.7,Math.max(1,4)));
        System.out.println(Math.max(1,Math.max(2,Math.max(3,4))));
        //power method
        System.out.println(Math.pow(2,3));
        System.out.println(Math.pow(2.34,4.45));
        System.out.println(Math.pow(2,4.1));
        System.out.println(Math.pow(4.5,2));
        System.out.println(Math.pow(-2.1,-1.2));
        System.out.println(Math.pow(-3.4,2));
        System.out.println(Math.pow(-3.5,3.4));
    }
}
